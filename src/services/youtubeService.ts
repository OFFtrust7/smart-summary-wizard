
import { toast } from 'sonner';

// Default API URL - will be overridden by configureYouTubeService
let API_URL = '';

interface SummaryResponse {
  success: boolean;
  script?: string;
  error?: string;
}

/**
 * Generate a summary for a YouTube video using the backend API
 * @param youtubeUrl The URL of the YouTube video to summarize
 * @returns A promise resolving to the summary result
 */
export async function generateYouTubeSummary(youtubeUrl: string): Promise<SummaryResponse> {
  try {
    // First check if we have a backend URL configured
    if (!API_URL) {
      console.warn("Backend API URL is not configured. Using simulated response.");
      // Provide a simulated response for demonstration/development
      await new Promise(resolve => setTimeout(resolve, 2000));
      return {
        success: true,
        script: `This is a simulated summary of the YouTube video at ${youtubeUrl}. In a production environment, this would be generated by the backend using OpenAI's Whisper for transcription and GPT-4 for summarization.

## Key Points:
1. The video discusses important concepts about the topic
2. The presenter highlights several key methodologies
3. There are practical examples shown throughout
4. The conclusion summarizes the main takeaways

This summary was generated without actually processing the video since we're in development mode.`
      };
    }

    console.log(`Making API request to: ${API_URL}/generate-script`);
    
    // Real API call
    const response = await fetch(`${API_URL}/generate-script`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ url: youtubeUrl }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      let errorData;
      
      try {
        errorData = JSON.parse(errorText);
      } catch (e) {
        errorData = { detail: errorText || 'Unknown error' };
      }
      
      console.error("YouTube API error:", errorData);
      return {
        success: false,
        error: errorData.detail || `Server error: ${response.status}`
      };
    }

    const data = await response.json();
    
    // Make sure we're getting the full script without truncation
    console.log("Received script length:", data.script?.length || 0);
    
    return {
      success: true,
      script: data.script
    };
  } catch (error) {
    console.error("YouTube summarization error:", error);
    return {
      success: false,
      error: error instanceof Error ? error.message : "Unable to connect to the summarization service"
    };
  }
}

/**
 * Configure the YouTube service with environment variables
 * This should be called when the application starts
 */
export function configureYouTubeService(backendUrl: string): void {
  if (!backendUrl) {
    console.error("YouTube service configuration failed: No backend URL provided");
    return;
  }
  
  API_URL = backendUrl;
  console.log(`YouTube service configured with backend URL: ${API_URL}`);
}
