
import { AIModelAdapter, AIModelResponse, AIModelOptions } from './interface';
import { env } from '@/config/env';

/**
 * Default implementation for the AI Model Adapter
 * Uses the backend API configured in environment settings
 */
export class DefaultAIModel implements AIModelAdapter {
  private apiUrl: string;

  constructor(apiUrl?: string) {
    this.apiUrl = apiUrl || '';
  }

  async generateResponse(prompt: string, options: AIModelOptions = {}): Promise<AIModelResponse> {
    try {
      // If API URL is missing, use mock response
      if (!this.apiUrl || this.apiUrl.trim() === '' || env.isDevelopment()) {
        console.log("Using simulated AI response due to missing API URL or development environment");
        await new Promise(resolve => setTimeout(resolve, 800));
        return {
          success: true,
          text: `This is a simulated response to your prompt: "${prompt}"\n\nIn a production environment, this would be generated by a real AI model through the backend API.`
        };
      }

      console.log(`Making AI API request to: ${this.apiUrl}/generate-text`);
      
      // Real API call with a timeout
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 10000); // 10-second timeout
      
      try {
        const response = await fetch(`${this.apiUrl}/generate-text`, {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({ 
            prompt,
            maxLength: options.maxLength,
            temperature: options.temperature,
            stream: options.stream
          }),
          signal: controller.signal
        });

        clearTimeout(timeoutId);

        if (!response.ok) {
          const errorText = await response.text();
          let errorData;
          
          try {
            errorData = JSON.parse(errorText);
          } catch (e) {
            errorData = { detail: errorText || 'Unknown error' };
          }
          
          console.error("AI API error:", errorData);
          return {
            success: false,
            error: errorData.detail || `Server error: ${response.status}`
          };
        }

        const data = await response.json();
        
        return {
          success: true,
          text: data.text
        };
      } catch (fetchError) {
        clearTimeout(timeoutId);
        throw fetchError;
      }
    } catch (error) {
      console.error("AI service error:", error);
      if (error.name === 'AbortError') {
        return {
          success: false,
          error: "Request timed out. The server took too long to respond."
        };
      } else {
        // Default to mock response in case of connection errors
        console.log("Connection error detected, falling back to mock response");
        await new Promise(resolve => setTimeout(resolve, 800));
        return {
          success: true,
          text: `I couldn't connect to the AI service, so I'm providing a fallback response. You asked: "${prompt}"\n\nThis is a simulated response since the backend API is currently unavailable.`
        };
      }
    }
  }
}
