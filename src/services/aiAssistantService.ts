
/**
 * Service for interacting with the AI Assistant API
 */
import { toast } from 'sonner';
import { env } from '@/config/env';

// Default API URL - will be overridden by configureAIAssistantService
let API_URL = '';

interface AIAssistantResponse {
  success: boolean;
  text?: string;
  error?: string;
}

/**
 * Generate text using the AI Assistant API
 * @param prompt The user's prompt for the AI assistant
 * @returns A promise resolving to the AI response
 */
export async function generateAIResponse(prompt: string): Promise<AIAssistantResponse> {
  try {
    // If API_URL is empty, use the mock response for development
    if (!API_URL || API_URL.trim() === '') {
      console.log("AI Assistant API URL is not configured. Using simulated response.");
      // Provide a simulated response for demonstration/development
      await new Promise(resolve => setTimeout(resolve, 1500));
      return {
        success: true,
        text: `This is a simulated response to your prompt: "${prompt}"\n\nIn a production environment, this would be generated by a real AI model through the backend API. The response would be more relevant and helpful based on your specific query.`
      };
    }

    console.log(`Making AI Assistant API request to: ${API_URL}/generate-text`);
    
    // Real API call
    const response = await fetch(`${API_URL}/generate-text`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ prompt }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      let errorData;
      
      try {
        errorData = JSON.parse(errorText);
      } catch (e) {
        errorData = { detail: errorText || 'Unknown error' };
      }
      
      console.error("AI Assistant API error:", errorData);
      return {
        success: false,
        error: errorData.detail || `Server error: ${response.status}`
      };
    }

    const data = await response.json();
    
    // Log the response length to ensure we're getting the full text
    console.log("Received AI response length:", data.text?.length || 0);
    
    return {
      success: true,
      text: data.text
    };
  } catch (error) {
    console.error("AI Assistant error:", error);
    return {
      success: false,
      error: error instanceof Error ? error.message : "Unable to connect to the AI assistant service"
    };
  }
}

/**
 * Configure the AI Assistant service with environment variables
 * This should be called when the application starts
 */
export function configureAIAssistantService(backendUrl: string): void {
  if (!backendUrl) {
    console.warn("AI Assistant service configuration failed: No backend URL provided");
    return;
  }
  
  API_URL = backendUrl;
  console.log(`AI Assistant service configured with backend URL: ${API_URL}`);
}
