
/**
 * Service for interacting with the AI Assistant API
 */
import { toast } from 'sonner';
import { env } from '@/config/env';

// Default API URL - will be overridden by configureAIAssistantService
let API_URL = '';

interface AIAssistantResponse {
  success: boolean;
  text?: string;
  error?: string;
}

/**
 * Generate text using the AI Assistant API
 * @param prompt The user's prompt for the AI assistant
 * @returns A promise resolving to the AI response
 */
export async function generateAIResponse(prompt: string): Promise<AIAssistantResponse> {
  try {
    // Ensure API_URL is set either from environment or configuration
    if (!API_URL && env.BACKEND_API_URL) {
      console.log("Setting API_URL from environment:", env.BACKEND_API_URL);
      API_URL = env.BACKEND_API_URL;
    }

    // If API_URL is still empty or in a testing environment, use the mock response
    if (!API_URL || API_URL.trim() === '' || env.isDevelopment()) {
      console.log("Using simulated AI Assistant response due to missing API URL or development environment");
      // Provide a simulated response for demonstration/development
      await new Promise(resolve => setTimeout(resolve, 800));
      return {
        success: true,
        text: `This is a simulated response to your prompt: "${prompt}"\n\nIn a production environment, this would be generated by a real AI model through the backend API. The response would be more relevant and helpful based on your specific query.`
      };
    }

    console.log(`Making AI Assistant API request to: ${API_URL}/generate-text`);
    
    // Real API call with a timeout
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 10000); // 10-second timeout
    
    try {
      const response = await fetch(`${API_URL}/generate-text`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({ prompt }),
        signal: controller.signal
      });

      clearTimeout(timeoutId);

      if (!response.ok) {
        const errorText = await response.text();
        let errorData;
        
        try {
          errorData = JSON.parse(errorText);
        } catch (e) {
          errorData = { detail: errorText || 'Unknown error' };
        }
        
        console.error("AI Assistant API error:", errorData);
        return {
          success: false,
          error: errorData.detail || `Server error: ${response.status}`
        };
      }

      const data = await response.json();
      
      return {
        success: true,
        text: data.text
      };
    } catch (fetchError) {
      clearTimeout(timeoutId);
      throw fetchError;
    }
  } catch (error) {
    console.error("AI Assistant error:", error);
    if (error.name === 'AbortError') {
      return {
        success: false,
        error: "Request timed out. The server took too long to respond."
      };
    } else {
      // Always default to mock response in case of connection errors
      console.log("Connection error detected, falling back to mock response");
      await new Promise(resolve => setTimeout(resolve, 800));
      return {
        success: true,
        text: `I couldn't connect to the AI service, so I'm providing a fallback response. You asked: "${prompt}"\n\nThis is a simulated response since the backend API is currently unavailable. In normal operation, you would receive a more helpful and relevant response to your query.`
      };
    }
  }
}

/**
 * Configure the AI Assistant service with environment variables
 * This should be called when the application starts
 */
export function configureAIAssistantService(backendUrl: string): void {
  if (!backendUrl) {
    console.warn("AI Assistant service configuration warning: No backend URL provided, using mock responses");
    return;
  }
  
  API_URL = backendUrl;
  console.log(`AI Assistant service configured with backend URL: ${API_URL}`);
}
